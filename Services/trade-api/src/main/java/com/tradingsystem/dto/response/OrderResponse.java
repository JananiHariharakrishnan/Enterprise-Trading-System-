package com.tradingsystem.dto.response;


import com.tradingsystem.enums.OrderSide;
import com.tradingsystem.enums.OrderStatus;

import java.math.BigDecimal;

public class OrderResponse {

    private String orderId;
    private OrderStatus status;
    private String message;
    private String symbol;
    private OrderSide side;
    private Integer quantity;
    private BigDecimal price;

    // Currency conversion tracking
    private String originalCurrency;  // e.g., "INR" if conversion occurred
    private BigDecimal originalPrice; // Price before USD conversion

    public OrderResponse() {
        // Empty Constructor
    }

    public String getOrderId() {
        return orderId;
    }

    public void setOrderId(String orderId) {
        this.orderId = orderId;
    }

    public OrderStatus getStatus() {
        return status;
    }

    public void setStatus(OrderStatus status) {
        this.status = status;
    }

    public String getMessage() {
        return message;
    }

    public void setMessage(String message) {
        this.message = message;
    }

    public String getSymbol() {
        return symbol;
    }

    public void setSymbol(String symbol) {
        this.symbol = symbol;
    }

    public OrderSide getSide() {
        return side;
    }

    public void setSide(OrderSide side) {
        this.side = side;
    }

    public Integer getQuantity() {
        return quantity;
    }

    public void setQuantity(Integer quantity) {
        this.quantity = quantity;
    }

    public BigDecimal getPrice() {
        return price;
    }

    public void setPrice(BigDecimal price) {
        this.price = price;
    }

    public String getOriginalCurrency() {
        return originalCurrency;
    }

    public void setOriginalCurrency(String originalCurrency) {
        this.originalCurrency = originalCurrency;
    }

    public BigDecimal getOriginalPrice() {
        return originalPrice;
    }

    public void setOriginalPrice(BigDecimal originalPrice) {
        this.originalPrice = originalPrice;
    }
}

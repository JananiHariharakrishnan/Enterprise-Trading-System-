CREATE SCHEMA IF NOT EXISTS tradingsystem;

DROP TABLE IF EXISTS tradingsystem.price_alerts;
DROP TABLE IF EXISTS tradingsystem.watchlist_entries;
DROP TABLE IF EXISTS tradingsystem.watchlists;
DROP TABLE IF EXISTS tradingsystem.instruments;
DROP TABLE IF EXISTS tradingsystem.accounts;

CREATE TABLE tradingsystem.accounts (
    id BIGINT PRIMARY KEY,
    account_reference VARCHAR(64) NOT NULL UNIQUE,
    cash_balance NUMERIC(18,2) NOT NULL,
    buying_power NUMERIC(18,2) NOT NULL,
    status VARCHAR(20) NOT NULL,
    version INT NOT NULL DEFAULT 0,
    last_updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE tradingsystem.instruments (
    symbol VARCHAR(20) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    asset_class VARCHAR(20) NOT NULL,
    currency CHAR(3) NOT NULL,
    tradable BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE tradingsystem.watchlists (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_on TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_on TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_watchlists_account FOREIGN KEY (account_id) REFERENCES tradingsystem.accounts (id),
    CONSTRAINT uq_watchlists_account_name UNIQUE (account_id, name),
    CONSTRAINT uq_watchlists_id_account UNIQUE (id, account_id),
    CONSTRAINT ck_watchlists_name_non_blank CHECK (TRIM(name) <> '')
);

CREATE TABLE tradingsystem.watchlist_entries (
    watchlist_id BIGINT NOT NULL,
    symbol VARCHAR(20) NOT NULL,
    added_on TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (watchlist_id, symbol),
    CONSTRAINT fk_watchlist_entries_watchlist FOREIGN KEY (watchlist_id) REFERENCES tradingsystem.watchlists (id) ON DELETE CASCADE,
    CONSTRAINT fk_watchlist_entries_instrument FOREIGN KEY (symbol) REFERENCES tradingsystem.instruments (symbol)
);

CREATE TABLE tradingsystem.price_alerts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    watchlist_id BIGINT NULL,
    symbol VARCHAR(20) NOT NULL,
    direction VARCHAR(20) NOT NULL,
    threshold NUMERIC(18,2) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    last_condition_met BOOLEAN NOT NULL DEFAULT FALSE,
    last_evaluated_price NUMERIC(18,2),
    last_quote_as_of TIMESTAMP,
    triggered_on TIMESTAMP,
    notification_status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    notification_attempts INT NOT NULL DEFAULT 0,
    last_notification_error VARCHAR(200),
    created_on TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_on TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_price_alerts_direction CHECK (direction IN ('ABOVE_OR_EQUAL', 'BELOW_OR_EQUAL', 'ABOVE', 'BELOW')),
    CONSTRAINT ck_price_alerts_status CHECK (status IN ('ACTIVE', 'TRIGGERED', 'DISABLED')),
    CONSTRAINT ck_price_alerts_notification_status CHECK (notification_status IN ('PENDING', 'SENT', 'FAILED')),
    CONSTRAINT ck_price_alerts_threshold_positive CHECK (threshold > 0),
    CONSTRAINT ck_price_alerts_notification_attempts_non_negative CHECK (notification_attempts >= 0)
);


CREATE INDEX ix_watchlists_account_created
    ON tradingsystem.watchlists (account_id, created_on DESC);

CREATE INDEX ix_watchlist_entries_symbol
    ON tradingsystem.watchlist_entries (symbol);

CREATE INDEX ix_price_alerts_account_status
    ON tradingsystem.price_alerts (account_id, status);

CREATE INDEX ix_price_alerts_symbol_status
    ON tradingsystem.price_alerts (symbol, status);

CREATE INDEX ix_price_alerts_watchlist_id
    ON tradingsystem.price_alerts (watchlist_id);

CREATE SYNONYM IF NOT EXISTS accounts FOR tradingsystem.accounts;
CREATE SYNONYM IF NOT EXISTS instruments FOR tradingsystem.instruments;
CREATE SYNONYM IF NOT EXISTS watchlists FOR tradingsystem.watchlists;
CREATE SYNONYM IF NOT EXISTS watchlist_entries FOR tradingsystem.watchlist_entries;
CREATE SYNONYM IF NOT EXISTS price_alerts FOR tradingsystem.price_alerts;

